#!/usr/bin/env node
// Builds per-country "list" catalogs from data/world-<name>.txt:
//   data/world-<name>.json, assets/data/world-<name>.min.json, docs/research/world-<name>.md
// Source format: `CC|Name~website~type;Name~website~type;...`
//   "^Name" = sub-brand (carriers: MVNO), trailing "*" = unverified,
//   a name starting with "—" is a country note (e.g. "no stock exchange"), not a pickable entry.
// Usage: node scripts/build-world-lists.mjs [carriers brokers ...]   (default: all)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const CATALOGS = {
  carriers: {
    title: 'World mobile carriers (SIM / eSIM)',
    unit: 'carriers',
    defType: cc => (cc === 'OTHER' ? 'esim' : 'mno'),
    subType: 'mvno',
    types: {},
    labels: { mno: 'operator', mvno: 'MVNO', esim: 'global eSIM' },
    otherLabel: 'Global eSIM providers',
  },
  brokers: {
    title: 'World investment brokers & platforms',
    unit: 'platforms',
    defType: () => 'broker',
    types: { b: 'broker', f: 'fund', r: 'robo', x: 'crypto', e: 'exchange' },
    labels: { broker: 'broker / trading app', fund: 'fund / asset manager', robo: 'robo / investing app', crypto: 'crypto exchange', exchange: 'exchange (reference)' },
    otherLabel: 'Global platforms',
  },
};

const slug = d => String(d || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
let dn = null;
try { dn = new Intl.DisplayNames(['en'], { type: 'region' }); } catch (_) {}

function build(name) {
  const cfg = CATALOGS[name];
  const src = join(ROOT, `data/world-${name}.txt`);
  const header = [], rows = [], notes = {}, errors = [], seen = new Set();
  readFileSync(src, 'utf8').split('\n').forEach((raw, i) => {
    const line = raw.trim();
    if (!line) return;
    if (line.startsWith('#')) { header.push(line.replace(/^#\s?/, '')); return; }
    const [cc, list] = line.split('|');
    if (!/^([A-Z]{2}|OTHER)$/.test(cc) || !list) { errors.push(`line ${i + 1}: ${line}`); return; }
    if (seen.has(cc)) errors.push(`duplicate country ${cc}`);
    seen.add(cc);
    for (let item of list.split(';')) {
      item = item.trim();
      if (!item) continue;
      const u = item.endsWith('*');
      if (u) item = item.slice(0, -1);
      let [n, web = '', t = ''] = item.split('~').map(s => s.trim());
      if (n.startsWith('—')) { (notes[cc] = notes[cc] || []).push(n.replace(/^—\s*/, '').replace(/^\(|\)$/g, '')); continue; }
      const sub = n.startsWith('^');
      if (sub) n = n.slice(1);
      if (!n) { errors.push(`line ${i + 1}: empty name`); continue; }
      if (t && !cfg.types[t]) { errors.push(`line ${i + 1}: unknown type ${t}`); continue; }
      const type = t ? cfg.types[t] : (sub && cfg.subType) ? cfg.subType : cfg.defType(cc);
      const r = { n, c: cc, t: type, web };
      if (u) r.u = 1;
      const logo = web && `assets/banks/${slug(web.split('/')[0])}.png`;
      if (logo && existsSync(join(ROOT, logo))) r.logo = logo;
      rows.push(r);
    }
  });
  if (errors.length) { console.error(`${name}:\n` + errors.join('\n')); process.exit(1); }

  writeFileSync(join(ROOT, `data/world-${name}.json`), '[\n' + rows.map(r => JSON.stringify(r)).join(',\n') + '\n]\n');
  mkdirSync(join(ROOT, 'assets/data'), { recursive: true });
  // Runtime rows skip reference-only entries (stock exchanges) so pickers suggest things a user holds an account with.
  writeFileSync(join(ROOT, `assets/data/world-${name}.min.json`),
    JSON.stringify(rows.filter(r => r.t !== 'exchange').map(r => [r.n, r.c, r.t, r.web.split('/')[0]])));

  const label = cc => (cc === 'OTHER' ? cfg.otherLabel : (dn && dn.of(cc)) || cc);
  const by = {};
  rows.forEach(r => (by[r.c] = by[r.c] || []).push(r));
  const ccs = [...seen].sort((a, b) => (a === 'OTHER') - (b === 'OTHER') || label(a).localeCompare(label(b)));
  const typeCounts = Object.entries(cfg.labels).map(([k, l]) => `${l}: ${rows.filter(r => r.t === k).length}`).join(' · ');
  const out = [`# ${cfg.title}`, '',
    `Generated by \`scripts/build-world-lists.mjs ${name}\` from \`data/world-${name}.txt\`. **${rows.length} ${cfg.unit} across ${ccs.filter(c => c !== 'OTHER').length} countries**${seen.has('OTHER') ? ` plus ${cfg.otherLabel.toLowerCase()}` : ''}.`, '',
    ...header.map(h => '> ' + h), '',
    `${typeCounts} · unverified: ${rows.filter(r => r.u).length}`, '',
    '| Country | Entries |', '|---|---|'];
  for (const cc of ccs) {
    const items = (by[cc] || []).map(r => `${r.n} _(${cfg.labels[r.t]})_${r.u ? ' — unverified' : ''}${r.web ? ` — ${r.web}` : ''}`);
    (notes[cc] || []).forEach(n => items.push(`_${n}_`));
    out.push(`| ${cc} ${label(cc)} | ${items.join('<br>')} |`);
  }
  mkdirSync(join(ROOT, 'docs/research'), { recursive: true });
  writeFileSync(join(ROOT, `docs/research/world-${name}.md`), out.join('\n') + '\n');
  console.log(`world-${name}: ${rows.length} entries, ${ccs.length} country groups, ${rows.filter(r => r.u).length} unverified`);
}

const want = process.argv.slice(2);
for (const name of want.length ? want : Object.keys(CATALOGS)) {
  if (!CATALOGS[name]) { console.error('unknown catalog ' + name); process.exit(1); }
  build(name);
}
