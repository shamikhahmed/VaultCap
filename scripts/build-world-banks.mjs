#!/usr/bin/env node
// Builds data/world-banks.json and docs/research/world-banks.md from the
// hand-researched source files in data/world-banks/*.txt.
//
// Source line format (see header of each .txt):
//   ## CC Country name | regulator | source URL ; source URL
//   > country note
//   name|type|app|web|swift|note        (trailing "*" on note = unverified)
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'data/world-banks');
const TYPES = { c: 'commercial', i: 'islamic', d: 'digital', m: 'microfinance', g: 'government', x: 'international', w: 'wallet' };
const APPS = { B: 'ios,android', A: 'android', I: 'ios', W: 'web', N: 'none', '?': '' };
const APP_LABEL = { 'ios,android': 'iOS · Android', android: 'Android', ios: 'iOS', web: 'Web only', none: '—', '': '?' };

const slug = d => String(d || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const host = w => String(w || '').split('/')[0];

const regions = [];
const banks = [];
const errors = [];

for (const file of readdirSync(SRC).filter(f => f.endsWith('.txt')).sort()) {
  const lines = readFileSync(join(SRC, file), 'utf8').split('\n');
  let region = null, country = null;
  lines.forEach((raw, i) => {
    const line = raw.trim();
    if (!line) return;
    if (line.startsWith('# Region:')) { region = { name: line.slice(9).trim(), file, intro: [], countries: [] }; regions.push(region); return; }
    if (line.startsWith('##')) {
      const [head, regulator = '', sources = ''] = line.slice(2).split('|').map(s => s.trim());
      const [cc, ...nameParts] = head.split(' ');
      country = { cc, name: nameParts.join(' '), regulator, sources: sources.split(';').map(s => s.trim()).filter(Boolean), notes: [], banks: [] };
      region.countries.push(country);
      return;
    }
    if (line.startsWith('#')) { if (region && !country) region.intro.push(line.replace(/^#\s?/, '')); return; }
    if (line.startsWith('>')) { country && country.notes.push(line.slice(1).trim()); return; }
    const parts = line.split('|');
    if (parts.length !== 6 || !country) { errors.push(`${file}:${i + 1}: ${line}`); return; }
    let [n, t, app, web, swift, note] = parts.map(s => s.trim());
    if (!TYPES[t] || !(app in APPS)) { errors.push(`${file}:${i + 1}: bad type/app: ${line}`); return; }
    const unverified = note.endsWith('*');
    note = note.replace(/\*$/, '').trim();
    const b = { n, c: country.cc, t: TYPES[t], app: APPS[app], web, swift, note };
    if (unverified) b.u = 1;
    const logo = web && `assets/banks/${slug(host(web))}.png`;
    if (logo && existsSync(join(ROOT, logo))) b.logo = logo;
    banks.push(b);
    country.banks.push(b);
  });
}

if (errors.length) { console.error('Parse errors:\n' + errors.join('\n')); process.exit(1); }
const dupes = new Set(); const seen = new Set();
for (const b of banks) { const k = b.c + '|' + b.n.toLowerCase(); if (seen.has(k)) dupes.add(k); seen.add(k); }
if (dupes.size) { console.error('Duplicate entries:\n' + [...dupes].join('\n')); process.exit(1); }

// JSON: one entry per line keeps diffs reviewable.
writeFileSync(join(ROOT, 'data/world-banks.json'), '[\n' + banks.map(b => JSON.stringify(b)).join(',\n') + '\n]\n');
// Slim runtime copy the app lazy-loads (served from assets/, which Pages and the
// Capacitor stage already ship): [name, country, type, logo domain].
mkdirSync(join(ROOT, 'assets/data'), { recursive: true });
writeFileSync(join(ROOT, 'assets/data/world-banks.min.json'), JSON.stringify(banks.map(b => [b.n, b.c, b.t, host(b.web)])));

// Report
const typeKeys = Object.values(TYPES);
const count = list => { const o = Object.fromEntries(typeKeys.map(k => [k, 0])); list.forEach(b => o[b.t]++); return o; };
const esc = s => String(s || '').replace(/\|/g, '\\|');
const countries = regions.flatMap(r => r.countries);
const tot = count(banks);
const out = [];
out.push('# World bank & banking-app catalog', '');
out.push(`Generated by \`scripts/build-world-banks.mjs\` from \`data/world-banks/*.txt\`. Machine-readable output: \`data/world-banks.json\`.`, '');
out.push(`**${banks.length} institutions across ${countries.length} countries/territories** — every ISO region in VaultCap's \`COUNTRIES\` list.`, '');
out.push('## How this was researched', '');
out.push('- Starting point for every country: the central bank or banking regulator\'s licensed-institution register (named per country below).');
out.push('- Web research for hard or fast-changing markets (Pacific islands, CEMAC/WAEMU, Eastern Caribbean, conflict-affected states, Gulf digital-bank licences, Nauru\'s 2025 bank handover). Those source links are listed per country.');
out.push('- Entries marked **unverified** could not be confirmed against a primary source during this pass (ownership changes, renames, small-market app availability). Treat them as leads.');
out.push('- `App` = official banking app availability: iOS · Android, Android only (e.g. sanctions-affected markets where apps were pulled from Apple\'s store), Web only, — (none), ? (not checked).');
out.push('- SWIFT/BIC is filled only for codes that are widely published (head-office 8-character codes). Blank means not recorded, not "none".');
out.push('- Logos: `logo` in the JSON points to a bundled file in `assets/banks/` when one exists. Everything else falls back to the app\'s initials tile. No third-party logo service is called. Logos are trademarks of their owners, used only to identify the institution.');
out.push('- Banking markets change. Re-check against the regulator before relying on a single entry.', '');
out.push('## Summary', '');
out.push('| Region | Countries | Total | ' + typeKeys.join(' | ') + ' | Unverified | With logo |');
out.push('|---|---|---|' + typeKeys.map(() => '---').join('|') + '|---|---|');
for (const r of regions) {
  const list = r.countries.flatMap(c => c.banks); const c = count(list);
  out.push(`| ${r.name} | ${r.countries.length} | ${list.length} | ${typeKeys.map(k => c[k]).join(' | ')} | ${list.filter(b => b.u).length} | ${list.filter(b => b.logo).length} |`);
}
out.push(`| **All** | **${countries.length}** | **${banks.length}** | ${typeKeys.map(k => `**${tot[k]}**`).join(' | ')} | **${banks.filter(b => b.u).length}** | **${banks.filter(b => b.logo).length}** |`, '');
out.push('## Countries', '');
for (const r of regions) {
  out.push(`### ${r.name}`, '');
  r.intro.filter(l => !/^(Line format|type:|app:|A trailing)/.test(l)).forEach(l => out.push('> ' + l));
  if (r.intro.length) out.push('');
  for (const c of r.countries) {
    out.push(`#### ${c.cc} — ${c.name} (${c.banks.length})`, '');
    out.push(`Regulator: ${c.regulator || '—'}${c.sources.length ? ' · Sources: ' + c.sources.map(s => s.startsWith('http') ? `<${s}>` : s).join(', ') : ''}`, '');
    c.notes.forEach(n => out.push('> ' + n));
    if (c.notes.length) out.push('');
    out.push('| Institution | Type | App | Website | SWIFT | Note |', '|---|---|---|---|---|---|');
    for (const b of c.banks) {
      out.push(`| ${esc(b.n)} | ${b.t} | ${APP_LABEL[b.app]} | ${esc(b.web)} | ${b.swift} | ${esc(b.note)}${b.u ? (b.note ? ' — ' : '') + '_unverified_' : ''} |`);
    }
    out.push('');
  }
}
mkdirSync(join(ROOT, 'docs/research'), { recursive: true });
writeFileSync(join(ROOT, 'docs/research/world-banks.md'), out.join('\n'));
console.log(`world-banks: ${banks.length} entries, ${countries.length} countries, ${banks.filter(b => b.logo).length} with bundled logo, ${banks.filter(b => b.u).length} unverified`);
