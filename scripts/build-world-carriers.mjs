#!/usr/bin/env node
// Builds data/world-carriers.json, assets/data/world-carriers.min.json and
// docs/research/world-carriers.md from data/world-carriers.txt.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const lines = readFileSync(join(ROOT, 'data/world-carriers.txt'), 'utf8').split('\n');
const header = [];
const rows = [];
const seen = new Set();
const errors = [];

lines.forEach((raw, i) => {
  const line = raw.trim();
  if (!line) return;
  if (line.startsWith('#')) { header.push(line.replace(/^#\s?/, '')); return; }
  const [cc, list] = line.split('|');
  if (!/^([A-Z]{2}|OTHER)$/.test(cc) || !list) { errors.push(`line ${i + 1}: ${line}`); return; }
  if (seen.has(cc)) errors.push(`duplicate country ${cc}`);
  seen.add(cc);
  for (let item of list.split(';')) {
    item = item.trim();
    const u = item.endsWith('*');
    if (u) item = item.slice(0, -1);
    let [n, web = ''] = item.split('~').map(s => s.trim());
    const mvno = n.startsWith('^');
    if (mvno) n = n.slice(1);
    if (!n) { errors.push(`line ${i + 1}: empty name`); continue; }
    const r = { n, c: cc, t: mvno ? 'mvno' : (cc === 'OTHER' ? 'esim' : 'mno'), web };
    if (u) r.u = 1;
    const logo = web && `assets/banks/${web.split('/')[0].toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}.png`;
    if (logo && existsSync(join(ROOT, logo))) r.logo = logo;
    rows.push(r);
  }
});
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

writeFileSync(join(ROOT, 'data/world-carriers.json'), '[\n' + rows.map(r => JSON.stringify(r)).join(',\n') + '\n]\n');
mkdirSync(join(ROOT, 'assets/data'), { recursive: true });
writeFileSync(join(ROOT, 'assets/data/world-carriers.min.json'), JSON.stringify(rows.map(r => [r.n, r.c, r.t, r.web.split('/')[0]])));

let names = {};
try {
  const dn = new Intl.DisplayNames(['en'], { type: 'region' });
  names = new Proxy({}, { get: (_, cc) => (cc === 'OTHER' ? 'Global eSIM providers' : dn.of(cc)) });
} catch (_) {}
const by = {};
rows.forEach(r => (by[r.c] = by[r.c] || []).push(r));
const ccs = Object.keys(by).sort((a, b) => (a === 'OTHER') - (b === 'OTHER') || String(names[a]).localeCompare(String(names[b])));
const out = ['# World mobile carriers (SIM / eSIM)', '',
  `Generated by \`scripts/build-world-carriers.mjs\` from \`data/world-carriers.txt\`. **${rows.length} carriers across ${ccs.length - 1} countries** plus global eSIM providers.`, '',
  ...header.map(h => '> ' + h), '',
  `Network operators: ${rows.filter(r => r.t === 'mno').length} · MVNOs / sub-brands: ${rows.filter(r => r.t === 'mvno').length} · global eSIM: ${rows.filter(r => r.t === 'esim').length} · unverified: ${rows.filter(r => r.u).length}`, '',
  '| Country | Carriers |', '|---|---|'];
for (const cc of ccs) {
  out.push(`| ${cc} ${names[cc] || ''} | ${by[cc].map(r => `${r.n}${r.t === 'mvno' ? ' (MVNO)' : ''}${r.u ? ' _(unverified)_' : ''}${r.web ? ` — ${r.web}` : ''}`).join('<br>')} |`);
}
mkdirSync(join(ROOT, 'docs/research'), { recursive: true });
writeFileSync(join(ROOT, 'docs/research/world-carriers.md'), out.join('\n') + '\n');
console.log(`world-carriers: ${rows.length} carriers, ${ccs.length} country groups, ${rows.filter(r => r.u).length} unverified`);
